"""Media files (photos, scans, PDFs, audio, video) and their links to people.

Originals are stored exactly as uploaded and never modified; web versions and thumbnails
are separate derived files generated by the worker.
"""

from __future__ import annotations

import datetime as dt
import uuid
from typing import Any

from sqlalchemy import BigInteger, Float, ForeignKey, Integer, String, Text, UniqueConstraint
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.dates import PartialDate
from app.core.enums import MediaKind, ProcessingStatus
from app.models.base import Base, TimestampMixin, UUIDPrimaryKeyMixin, text_enum, utcnow_column
from app.models.genealogy_base import (
    AuthoredMixin,
    SoftDeleteMixin,
    TreeScopedMixin,
    partial_date,
    sort_date_column,
)


class MediaFile(
    UUIDPrimaryKeyMixin, TreeScopedMixin, AuthoredMixin, SoftDeleteMixin, TimestampMixin, Base
):
    __tablename__ = "media_files"

    kind: Mapped[MediaKind] = mapped_column(text_enum(MediaKind, "media_kind"), index=True)
    # The original, byte for byte as uploaded.
    original_key: Mapped[str] = mapped_column(String(500))
    original_filename: Mapped[str] = mapped_column(String(500))
    mime_type: Mapped[str] = mapped_column(String(100))
    size: Mapped[int] = mapped_column(BigInteger)
    sha256: Mapped[str] = mapped_column(String(64), index=True)
    # Derived files (may be regenerated at any time).
    web_key: Mapped[str | None] = mapped_column(String(500))
    thumb_key: Mapped[str | None] = mapped_column(String(500))
    processing_status: Mapped[ProcessingStatus] = mapped_column(
        text_enum(ProcessingStatus, "processing_status"),
        default=ProcessingStatus.pending,
        server_default=ProcessingStatus.pending,
    )
    processing_error: Mapped[str | None] = mapped_column(Text)
    width: Mapped[int | None] = mapped_column(Integer)
    height: Mapped[int | None] = mapped_column(Integer)
    duration_seconds: Mapped[float | None] = mapped_column(Float)
    # Description of the item itself.
    title: Mapped[str | None] = mapped_column(String(300))
    description: Mapped[str | None] = mapped_column(Text)
    date: Mapped[PartialDate] = partial_date("date")
    date_sort: Mapped[dt.date | None] = sort_date_column("date")
    place_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("places.id", ondelete="SET NULL"), index=True
    )

    people: Mapped[list[MediaPerson]] = relationship(
        back_populates="media", cascade="all, delete-orphan", passive_deletes=True
    )


class MediaPerson(UUIDPrimaryKeyMixin, Base):
    """A person appearing in / related to a media item. `region` marks their face in a
    group photo as fractions of the image size: {"x", "y", "w", "h"} in 0..1."""

    __tablename__ = "media_persons"
    __table_args__ = (UniqueConstraint("media_id", "person_id"),)

    media_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("media_files.id", ondelete="CASCADE"), index=True
    )
    person_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("persons.id", ondelete="CASCADE"), index=True
    )
    region: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    # Position in the person's gallery.
    sort_order: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    created_at: Mapped[dt.datetime] = utcnow_column()

    media: Mapped[MediaFile] = relationship(back_populates="people")
